#!/usr/bin/env python3
"""Scan ../travel and write travel-assets/manifest.js.

Run it again whenever you add photos:

    python travel-assets/build_manifest.py

What it does
- lists every image under travel/<country>_travel/ (recursively)
- tags each photo with its city = name of the first sub-folder (lower-case)
- flat files such as berlin3.jpg are tagged by file-name prefix (see PREFIX)
- the same photo stored both flat and in a sub-folder is listed once
  (same file name + same size -> the sub-folder copy wins)

The pages work without re-running it for cities that are still empty
(they fall back to the GitHub API), but new photos in cities that already
have some only show up after you run this script and push manifest.js.
"""
import json
import os
import re
import unicodedata
from datetime import datetime, timezone

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
TRAVEL = os.path.join(ROOT, "travel")
IMG_EXT = (".jpg", ".jpeg", ".png", ".webp", ".gif")

# flat file name (without trailing digits, lower-case) -> city key
PREFIX = {
    "berlin": "berlin",
    "bremen": "bremen",
    "düsseldorf": "düsseldorf",
    "frankfort": "frankfurt",
    "frankfurt": "frankfurt",
    "hamburg": "hamburg",
    "potsdam": "potsdam",
}


def nfc(s):
    return unicodedata.normalize("NFC", s)


def natural_key(s):
    return [int(t) if t.isdigit() else t.lower() for t in re.split(r"(\d+)", s)]


def main():
    folders = {}
    for country in sorted(os.listdir(TRAVEL)):
        cdir = os.path.join(TRAVEL, country)
        if not os.path.isdir(cdir):
            continue
        found = {}
        for dirpath, _dirs, files in os.walk(cdir):
            for name in files:
                if not name.lower().endswith(IMG_EXT):
                    continue
                full = os.path.join(dirpath, name)
                rel = nfc(os.path.relpath(full, TRAVEL).replace(os.sep, "/"))
                sub = nfc(os.path.relpath(dirpath, cdir).replace(os.sep, "/"))
                if sub == ".":
                    stem = os.path.splitext(nfc(name))[0]
                    city = PREFIX.get(re.sub(r"\d+$", "", stem).lower())
                else:
                    city = sub.split("/")[0].lower()
                dedupe = (nfc(name).lower(), os.path.getsize(full))
                entry = {"p": rel, "c": city}
                old = found.get(dedupe)
                if old is None or (old["c"] is None and city is not None):
                    found[dedupe] = entry
                elif old["c"] is not None and city is not None and old["p"] > rel:
                    found[dedupe] = entry
        items = sorted(found.values(), key=lambda e: natural_key(e["p"]))
        if items:
            folders[nfc(country)] = items

    payload = {
        "generated": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
        "folders": folders,
    }
    out = os.path.join(HERE, "manifest.js")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("/* generated by build_manifest.py - do not edit */\n")
        fh.write("window.TRAVEL_MANIFEST=")
        json.dump(payload, fh, ensure_ascii=False, separators=(",", ":"))
        fh.write(";\n")
    total = sum(len(v) for v in folders.values())
    print(f"wrote {out}: {total} photos in {len(folders)} folders")
    for k, v in folders.items():
        print(f"  {k}: {len(v)}")


if __name__ == "__main__":
    main()
